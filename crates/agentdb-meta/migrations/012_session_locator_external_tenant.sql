-- M26 Phase 1b correction: store the external tenant id on
-- the locator directly. The original migration recorded
-- `tenant_internal_id`, but the in-process `TenantRegistry`
-- assigns those ids per local KV — they are NOT globally
-- meaningful and don't index any cross-cluster table today.
-- Resolving an external tenant identity via internal_id
-- requires a populated `tenants` table, which production
-- mints never write to.
--
-- Adding `tenant_external_id` lets the M26 fork-handler path
-- (and future routing) read auth-bound tenant identity in
-- one query without joining to `tenants`. Old `tenant_internal_id`
-- stays in place — keeping the column avoids a destructive
-- migration on a brand-new table that's safe to leave at 0
-- for legacy callers.
ALTER TABLE session_locators ADD COLUMN tenant_external_id TEXT;
